export const DICTIONARIES = { de, en, sv };
export const LANGUAGES = { de: "Deutsch", en: "English", sv: "Svenska" };

let lang = "de";

export function detectLanguage(saved) {
  if (saved && DICTIONARIES[saved]) return saved;
  const nav = (typeof navigator !== "undefined" && navigator.language || "de").slice(0, 2).toLowerCase();
  return DICTIONARIES[nav] ? nav : "de";
}

export function setLanguage(l) {
  lang = DICTIONARIES[l] ? l : "de";
  if (typeof document !== "undefined") document.documentElement.lang = lang;
}

export const getLanguage = () => lang;

export function t(key, vars) {
  const str = DICTIONARIES[lang][key] ?? de[key] ?? key;
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

// Statische Texte im HTML: data-i18n, data-i18n-placeholder, -title, -aria
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
}
